/**
 * Stax build: CSS (purge, split, minify, RTL) and JS (minify).
 *
 * Usage: npm install && npm run build
 *
 * Sources (edit these):
 *   assets/css/src/stax-1x.css        the 1.2.2 stylesheet; source of the lean CSS and of the legacy file
 *   assets/css/src/stax-2.css         2.0 additions (accessibility, sticky sidebars, scrollers, fixes)
 *   assets/css/src/blocks.css         block styles (front end and editor)
 *   assets/css/src/compat/<name>.css  hand-written plugin compatibility rules
 *   inc/Customizer/builder/assets/scss/style.scss   header/footer builder
 *   assets/js/index.js, assets/js/lightbox.js, assets/js/hfg/*.js (bundled to hfg/app.js)
 *
 * Outputs (do not edit): assets/css/index(.min).css, assets/css/compat/*.css, assets/css/legacy/stax-1x.min.css,
 * assets/css/legacy/stax-1x-rules.json (1.x rules left out of the lean file, for the style switch compatibility CSS),
 * inc/Customizer/builder/assets/css/style(.min).css, assets/js/*.min.js.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';
import cssnano from 'cssnano';
import rtlcss from 'rtlcss';
import { PurgeCSS } from 'purgecss';
import * as sass from 'sass';
import * as esbuild from 'esbuild';
import { globSync } from 'glob';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const r = (p) => path.join(root, p);
const read = (p) => fs.readFileSync(r(p), 'utf8');
const write = (p, s) => {
	fs.mkdirSync(path.dirname(r(p)), { recursive: true });
	fs.writeFileSync(r(p), s);
	console.log(`${p.padEnd(52)} ${(Buffer.byteLength(s) / 1024).toFixed(1)} KB`);
};

/* Plugin-specific selectors move to files that load only when that plugin is active. */
const COMPAT = {
	woocommerce: /woocommerce|\.wc-|wc-block|\.product\b|\.products\b|\.cart\b|\.checkout\b|shop_table|\.onsale|star-rating|added_to_cart|mini_cart|\.stx-nav-cart|header_cart/,
	buddypress: /buddypress|\.bp-|bp-nouveau|#item-|\.item-list|\.activity|\.members-|\.groups-/,
	bbpress: /bbp|bbpress/,
	elementor: /elementor/,
};

const minify = async (css) => (await postcss([cssnano({ preset: ['default', { discardComments: { removeAll: true } }] })]).process(css, { from: undefined })).css;
const toRtl = (css) => postcss([rtlcss()]).process(css, { from: undefined }).css;

/**
 * Writes name.css and name.min.css. RTL: the stylesheets carry their own [dir=rtl] rules
 * (language_attributes() prints dir="rtl"), so no flipped copies are generated by default.
 */
async function emit(base, css, { rtl = false, pretty = true } = {}) {
	if (pretty) {
		write(`${base}.css`, css);
	}
	write(`${base}.min.css`, await minify(css));
	if (rtl) {
		const rtlCss = toRtl(css);
		if (pretty) {
			write(`${base}-rtl.css`, rtlCss);
		}
		write(`${base}-rtl.min.css`, await minify(rtlCss));
	}
}

/** Moves every selector matching `pattern` into a new root, keeping @media/@supports wrappers. */
function extract(rootNode, pattern) {
	const out = postcss.root();
	rootNode.walkRules((rule) => {
		if (rule.parent.type === 'atrule' && /keyframes/i.test(rule.parent.name)) {
			return;
		}
		const matched = rule.selectors.filter((s) => pattern.test(s));
		if (!matched.length) {
			return;
		}
		const kept = rule.selectors.filter((s) => !pattern.test(s));
		const copy = rule.clone({ selectors: matched });
		let target = out;
		const chain = [];
		for (let p = rule.parent; p && p.type === 'atrule'; p = p.parent) {
			chain.unshift(p);
		}
		for (const at of chain) {
			let existing = target.nodes.find((n) => n.type === 'atrule' && n.name === at.name && n.params === at.params);
			if (!existing) {
				existing = at.clone({ nodes: [] });
				target.append(existing);
			}
			target = existing;
		}
		target.append(copy);
		if (kept.length) {
			rule.selectors = kept;
		} else {
			rule.remove();
		}
	});
	rootNode.walkAtRules((at) => {
		if (at.nodes && at.nodes.length === 0) {
			at.remove();
		}
	});
	return out;
}

const norm = (s) => s.replace(/\s+/g, ' ').trim();
const atChain = (node) => {
	const chain = [];
	for (let p = node.parent; p && p.type === 'atrule'; p = p.parent) {
		chain.unshift(p);
	}
	return chain;
};
const chainKey = (node) => atChain(node).map((p) => `@${p.name} ${norm(p.params)}`).join('|');
const classesOf = (selector) => [...new Set([...selector.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)].map((m) => m[1]))];

/**
 * Writes assets/css/legacy/stax-1x-rules.json: every 1.x rule the lean stylesheet left out, indexed by the
 * classes that only those rules use (Bootstrap utilities such as row, col-md-6, btn, d-flex, ...).
 * When a site switches from the 1.x stylesheet to the lean one, Stax\Style_Switch scans its content for
 * these classes and keeps only the matching rules, so content built with 1.x classes looks the same.
 */
async function writeLegacyRules(legacy, leanCss) {
	const kept = new Set();
	const known = new Set();
	const keptKeyframes = new Set();
	postcss.parse(leanCss).walk((node) => {
		if (node.type === 'atrule' && /keyframes$/i.test(node.name)) {
			keptKeyframes.add(node.params);
		}
		if (node.type !== 'rule' || /keyframes$/i.test(node.parent.name || '')) {
			return;
		}
		const key = chainKey(node);
		node.selectors.forEach((sel) => {
			kept.add(key + '##' + norm(sel));
			classesOf(sel).forEach((c) => known.add(c));
		});
	});

	// Dropped selectors with their @media/@supports wrappers; selectors without a class (a handful of
	// Bootstrap reboot rules for rare elements) are left out.
	const dropped = postcss.root();
	const keyframes = {};
	postcss.parse(legacy).walk((node) => {
		if (node.type === 'atrule' && /keyframes$/i.test(node.name)) {
			if (!keptKeyframes.has(node.params)) {
				keyframes[node.params] = node.toString();
			}
			return;
		}
		if (node.type !== 'rule' || /keyframes$/i.test(node.parent.name || '')) {
			return;
		}
		const key = chainKey(node);
		const selectors = node.selectors.filter((sel) => !kept.has(key + '##' + norm(sel)) && classesOf(sel).length);
		if (!selectors.length) {
			return;
		}
		let target = dropped;
		for (const at of atChain(node)) {
			const params = norm(at.params);
			let existing = target.nodes.find((n) => n.type === 'atrule' && n.name === at.name && norm(n.params) === params);
			if (!existing) {
				existing = at.clone({ nodes: [] });
				target.append(existing);
			}
			target = existing;
		}
		target.append(node.clone({ selectors }));
	});

	const media = [''];
	const decls = [];
	const declIndex = new Map();
	const rules = [];
	const index = {};
	postcss.parse(await minify(dropped.toString())).walkRules((rule) => {
		const wrap = atChain(rule).map((p) => `@${p.name} ${p.params}`).join('|');
		let m = media.indexOf(wrap);
		if (m < 0) {
			m = media.push(wrap) - 1;
		}
		const body = rule.nodes.map((n) => n.toString()).join(';');
		if (!declIndex.has(body)) {
			declIndex.set(body, decls.push(body) - 1);
		}
		for (const sel of rule.selectors) {
			const id = rules.push([m, sel, declIndex.get(body)]) - 1;
			for (const c of classesOf(sel)) {
				if (!known.has(c)) {
					(index[c] = index[c] || []).push(id);
				}
			}
		}
	});

	const minKeyframes = {};
	for (const [name, css] of Object.entries(keyframes)) {
		minKeyframes[name] = await minify(css);
	}

	write('assets/css/legacy/stax-1x-rules.json', JSON.stringify({ version: 1, known: [...known].sort(), media, decls, rules, index, keyframes: minKeyframes }));
}

async function buildCss() {
	const safelistTokens = read('bin/css-safelist.txt').split('\n').filter((l) => l && !l.startsWith('#'));
	const content = globSync(['**/*.php', 'assets/js/index.js', 'assets/js/lightbox.js', 'assets/js/hfg/*.js'], { cwd: root, ignore: ['node_modules/**', 'dist/**'] }).map((f) => r(f));

	const legacy = read('assets/css/src/stax-1x.css');

	// Full 1.2.2 stylesheet plus the 2.0 additions, for sites that keep "Load the full 1.x stylesheet" on
	// (Customizer > Performance). Sites updated from 1.x start with it on, so nothing changes visually.
	write('assets/css/legacy/stax-1x.min.css', await minify(legacy + '\n' + read('assets/css/src/stax-2.css') + '\n' + read('assets/css/src/blocks.css')));

	const [purged] = await new PurgeCSS().purge({
		content: [...content, { raw: safelistTokens.join(' '), extension: 'html' }],
		css: [{ raw: legacy }],
		defaultExtractor: (c) => c.match(/[A-Za-z0-9_-]+/g) || [],
		safelist: {
			standard: [/^wp-/, /^has-/, /^is-/, /^align(wide|full|left|right|center|none)$/, /^screen-reader/, /^sticky$/, /^bypostauthor$/, /^gallery/, /^widget/, /^menu-/, /^current/, /^page_item/, /^comment/, /^children$/, /^post-/, /^format-/, /^svq-masonry/, /^svq--/, /^svq-overlay/, /^aspect-ratio/, /^animated$/, /^(fade|slide|zoom|bounce|flip|rotate)(In|Out)/, /^swiper/, /touchevents$/, /^js$/, /^no-js$/, /^rtl$/, /^admin-bar$/, /^logged-in$/, /^error404$/, /^layout-/],
		},
		keyframes: true,
		fontFace: true,
		variables: false,
	});

	await writeLegacyRules(legacy, purged.css);

	const core = postcss.parse(purged.css);
	const compat = {};
	for (const [name, pattern] of Object.entries(COMPAT)) {
		compat[name] = extract(core, pattern);
	}

	const header = '/*! Stax 2.0 | generated by bin/build.mjs from assets/css/src | GPL-3.0-or-later */\n';
	// The icon font rules are bundled into the core file (one request less); paths are rebased to assets/css/.
	const icons = read('assets/fonts/style.css').replace(/url\('stax\./g, "url('../fonts/stax.");
	await emit('assets/css/index', header + icons + '\n' + core.toString() + '\n' + read('assets/css/src/stax-2.css') + '\n' + read('assets/css/src/blocks.css'));

	for (const [name, rootNode] of Object.entries(compat)) {
		const extra = fs.existsSync(r(`assets/css/src/compat/${name}.css`)) ? read(`assets/css/src/compat/${name}.css`) : '';
		await emit(`assets/css/compat/${name}`, header + rootNode.toString() + '\n' + extra);
	}

	// Hand-written compat files with no 1.x rules (LMS plugins, EDD, ...).
	for (const file of globSync('assets/css/src/compat/*.css', { cwd: root })) {
		const name = path.basename(file, '.css');
		if (!COMPAT[name]) {
			await emit(`assets/css/compat/${name}`, header + read(file));
		}
	}

	await emit('assets/css/lightbox', read('assets/css/src/lightbox.css'));
	// Editor styles: same purge, plus editor-only classes. WordPress scopes them at runtime, so size matters.
	const [editor] = await new PurgeCSS().purge({
		content: [...content, { raw: safelistTokens.join(' '), extension: 'html' }],
		css: [{ raw: read('assets/css/src/style-editor.css') }],
		defaultExtractor: (c) => c.match(/[A-Za-z0-9_-]+/g) || [],
		safelist: { standard: [/^wp-/, /^has-/, /^is-/, /^editor-/, /^block-editor/, /^align/, /^screen-reader/, /^block-/] },
		keyframes: true,
		fontFace: true,
	});
	await emit('assets/css/style-editor', editor.css + '\n' + read('assets/css/src/editor-base.css') + '\n' + read('assets/css/src/blocks.css'));

	// Header and footer builder (the old minified file carried a 55 KB inline source map).
	const hfg = sass.compile(r('inc/Customizer/builder/assets/scss/style.scss'), { style: 'expanded', sourceMap: false, quietDeps: true, silenceDeprecations: ['import', 'global-builtin', 'slash-div', 'color-functions'] }).css;
	await emit('inc/Customizer/builder/assets/css/style', hfg);
}

async function buildJs() {
	// Header/footer builder script, bundled from its ES module sources (assets/js/hfg/index.js).
	await esbuild.build({ entryPoints: [r('assets/js/hfg/index.js')], outfile: r('assets/js/hfg/app.js'), bundle: true, format: 'iife', target: 'es2017', logLevel: 'silent' });

	for (const file of ['assets/js/index.js', 'assets/js/lightbox.js', 'assets/js/hfg/app.js']) {
		const out = file.replace(/\.js$/, '.min.js');
		await esbuild.build({ entryPoints: [r(file)], outfile: r(out), minify: true, target: 'es2017', legalComments: 'none', logLevel: 'silent' });
		console.log(`${out.padEnd(52)} ${(fs.statSync(r(out)).size / 1024).toFixed(1)} KB`);
	}
}

const only = process.argv[2];
if (!only || only === 'css') {
	await buildCss();
}
if (!only || only === 'js') {
	await buildJs();
}
